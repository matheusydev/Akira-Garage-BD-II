CREATE OR REPLACE FUNCTION VALIDAR_SERVICO()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.ID_SERVICO IS NULL THEN
        RAISE EXCEPTION 'O ID DO SERVICO NAO PODE SER NULO';
    ELSIF NEW.ID_SERVICO < 0 THEN
        RAISE EXCEPTION 'O ID DO SERVICO NAO PODE SER NEGATIVO';
    ELSIF TG_OP = 'INSERT' AND EXISTS (SELECT 1 FROM SERVICO WHERE ID_SERVICO = NEW.ID_SERVICO) THEN
        RAISE EXCEPTION 'JA EXISTE UM SERVICO COM O ID %', NEW.ID_SERVICO;
    ELSIF NEW.ID_FUNCIONARIO IS NULL THEN
        RAISE EXCEPTION 'O ID DO FUNCIONARIO RESPONSAVEL NAO PODE SER NULO';
    ELSIF NOT EXISTS (SELECT 1 FROM FUNCIONARIO WHERE ID_FUNCIONARIO = NEW.ID_FUNCIONARIO) THEN
        RAISE EXCEPTION 'O FUNCIONARIO DE ID % NAO ESTA CADASTRADO', NEW.ID_FUNCIONARIO;
    ELSIF NEW.DESCRICAO IS NULL OR NEW.DESCRICAO = '' THEN
        RAISE EXCEPTION 'A DESCRICAO DO SERVICO NAO PODE SER NULA OU VAZIA';
    ELSIF NEW.VALOR IS NULL OR NEW.VALOR <= 0 THEN
        RAISE EXCEPTION 'O VALOR DO SERVICO DEVE SER MAIOR QUE ZERO';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

