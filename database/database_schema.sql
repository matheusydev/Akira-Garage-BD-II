-- -------------------
-- TRIGGER: OS_PECA — valida estoque, baixa e soma no VALOR_FINAL
-- -------------------
CREATE OR REPLACE FUNCTION VALIDAR_E_BAIXAR_ESTOQUE_OS_PECA()
RETURNS TRIGGER AS $$
DECLARE
    V_STATUS_OS  VARCHAR(1);
    V_ESTOQUE    INT;
    V_NOME_PECA  VARCHAR;
    V_VALOR_UNIT FLOAT;
BEGIN
    SELECT STATUS INTO V_STATUS_OS FROM OS WHERE ID_OS = NEW.ID_OS;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'OS DE ID % NAO ENCONTRADA', NEW.ID_OS;
    END IF;
    IF V_STATUS_OS = 'F' THEN
        RAISE EXCEPTION 'NAO E POSSIVEL ADICIONAR PECA EM UMA OS JA FECHADA (ID_OS: %)', NEW.ID_OS;
    END IF;

    SELECT NOME, ESTOQUE, VALOR_UNITARIO
    INTO V_NOME_PECA, V_ESTOQUE, V_VALOR_UNIT
    FROM PECA WHERE ID_PECA = NEW.ID_PECA;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'PECA DE ID % NAO ENCONTRADA', NEW.ID_PECA;
    END IF;
    IF NEW.QUANTIDADE <= 0 THEN
        RAISE EXCEPTION 'A QUANTIDADE DEVE SER MAIOR QUE ZERO';
    END IF;
    IF V_ESTOQUE < NEW.QUANTIDADE THEN
        RAISE EXCEPTION 'ESTOQUE INSUFICIENTE PARA A PECA "%" (ESTOQUE: %, SOLICITADO: %)',
            V_NOME_PECA, V_ESTOQUE, NEW.QUANTIDADE;
    END IF;

    UPDATE PECA
    SET ESTOQUE = ESTOQUE - NEW.QUANTIDADE
    WHERE ID_PECA = NEW.ID_PECA;

    UPDATE OS
    SET VALOR_FINAL = VALOR_FINAL + (V_VALOR_UNIT * NEW.QUANTIDADE)
    WHERE ID_OS = NEW.ID_OS;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER DISPARAR_VALIDAR_OS_PECA
BEFORE INSERT ON OS_PECA
FOR EACH ROW
EXECUTE PROCEDURE VALIDAR_E_BAIXAR_ESTOQUE_OS_PECA();

