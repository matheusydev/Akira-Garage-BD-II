-- -------------------
CREATE OR REPLACE FUNCTION VALIDAR_OS()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.ID_OS IS NULL THEN
        RAISE EXCEPTION 'O ID DA OS NAO PODE SER NULO';
    ELSIF NEW.ID_OS < 0 THEN
        RAISE EXCEPTION 'O ID DA OS NAO PODE SER NEGATIVO';
    ELSIF TG_OP = 'INSERT' AND EXISTS (SELECT 1 FROM OS WHERE ID_OS = NEW.ID_OS) THEN
        RAISE EXCEPTION 'JA EXISTE UMA OS COM O ID %', NEW.ID_OS;
    ELSIF NEW.ID_POSSE IS NULL THEN
        RAISE EXCEPTION 'O ID DA POSSE NAO PODE SER NULO';
    ELSIF NOT EXISTS (SELECT 1 FROM POSSE WHERE ID_POSSE = NEW.ID_POSSE) THEN
        RAISE EXCEPTION 'A POSSE DE ID % NAO ESTA CADASTRADA', NEW.ID_POSSE;
    ELSIF NEW.STATUS NOT IN ('A', 'F') THEN
        RAISE EXCEPTION 'STATUS INVALIDO: USE "A" PARA ABERTA OU "F" PARA FECHADA';
    ELSIF NEW.VALOR_FINAL < 0 THEN
        RAISE EXCEPTION 'O VALOR FINAL DA OS NAO PODE SER NEGATIVO';
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF OLD.STATUS = 'F' THEN
            RAISE EXCEPTION 'NAO E PERMITIDO ALTERAR UMA OS JA FECHADA (ID_OS: %)', OLD.ID_OS;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

