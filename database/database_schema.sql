CREATE OR REPLACE FUNCTION VALIDAR_VEICULO()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.ID_VEICULO IS NULL THEN
        RAISE EXCEPTION 'O ID DO VEICULO NAO PODE SER NULO';
    ELSIF NEW.ID_VEICULO < 0 THEN
        RAISE EXCEPTION 'O ID DO VEICULO NAO PODE SER NEGATIVO';
    ELSIF TG_OP = 'INSERT' AND EXISTS (SELECT 1 FROM VEICULO WHERE ID_VEICULO = NEW.ID_VEICULO) THEN
        RAISE EXCEPTION 'JA EXISTE UM VEICULO COM O ID %', NEW.ID_VEICULO;
    ELSIF NEW.ID_MODELO IS NULL THEN
        RAISE EXCEPTION 'O ID DO MODELO NAO PODE SER NULO';
    ELSIF NOT EXISTS (SELECT 1 FROM MODELO WHERE ID_MODELO = NEW.ID_MODELO) THEN
        RAISE EXCEPTION 'O MODELO DE ID % NAO ESTA CADASTRADO', NEW.ID_MODELO;
    ELSIF NEW.PLACA IS NULL OR NEW.PLACA = '' THEN
        RAISE EXCEPTION 'A PLACA NAO PODE SER NULA OU VAZIA';
    ELSIF CHAR_LENGTH(NEW.PLACA) <> 7 THEN
        RAISE EXCEPTION 'A PLACA DEVE TER EXATAMENTE 7 CARACTERES';
    ELSIF TG_OP = 'INSERT' AND EXISTS (SELECT 1 FROM VEICULO WHERE PLACA = NEW.PLACA) THEN
        RAISE EXCEPTION 'JA EXISTE UM VEICULO COM A PLACA %', NEW.PLACA;
    ELSIF TG_OP = 'UPDATE' AND EXISTS (SELECT 1 FROM VEICULO WHERE PLACA = NEW.PLACA AND ID_VEICULO <> NEW.ID_VEICULO) THEN
        RAISE EXCEPTION 'JA EXISTE OUTRO VEICULO COM A PLACA %', NEW.PLACA;
    ELSIF NEW.ANO IS NULL THEN
        RAISE EXCEPTION 'O ANO DO VEICULO NAO PODE SER NULO';
    ELSIF NEW.ANO < 1886 OR NEW.ANO > EXTRACT(YEAR FROM CURRENT_DATE) THEN
        RAISE EXCEPTION 'O ANO DEVE ESTAR ENTRE 1886 E O ANO ATUAL (%)', EXTRACT(YEAR FROM CURRENT_DATE);
    ELSIF NEW.COR IS NULL OR NEW.COR = '' THEN
        RAISE EXCEPTION 'A COR DO VEICULO NAO PODE SER NULA OU VAZIA';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER DISPARAR_VALIDAR_VEICULO
BEFORE INSERT OR UPDATE ON VEICULO
FOR EACH ROW
EXECUTE PROCEDURE VALIDAR_VEICULO();

