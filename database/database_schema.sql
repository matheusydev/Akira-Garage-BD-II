-- -------------------
-- TRIGGER: CLIENTE
-- -------------------
CREATE OR REPLACE FUNCTION VALIDAR_CLIENTE()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.ID_CLIENTE IS NULL THEN
        RAISE EXCEPTION 'O ID DO CLIENTE NAO PODE SER NULO';
    ELSIF NEW.ID_CLIENTE < 0 THEN
        RAISE EXCEPTION 'O ID DO CLIENTE NAO PODE SER NEGATIVO';
    ELSIF TG_OP = 'INSERT' AND EXISTS (SELECT 1 FROM CLIENTE WHERE ID_CLIENTE = NEW.ID_CLIENTE) THEN
        RAISE EXCEPTION 'JA EXISTE UM CLIENTE COM O ID %', NEW.ID_CLIENTE;
    ELSIF NEW.CPF IS NULL THEN
        RAISE EXCEPTION 'O CPF DO CLIENTE NAO PODE SER NULO';
    ELSIF CHAR_LENGTH(NEW.CPF) <> 11 THEN
        RAISE EXCEPTION 'O CPF DEVE TER EXATAMENTE 11 DIGITOS';
    ELSIF NEW.CPF ~ '[^0-9]' THEN
        RAISE EXCEPTION 'O CPF DEVE CONTER APENAS DIGITOS NUMERICOS';
    ELSIF TG_OP = 'INSERT' AND EXISTS (SELECT 1 FROM CLIENTE WHERE CPF = NEW.CPF) THEN
        RAISE EXCEPTION 'JA EXISTE UM CLIENTE COM O CPF %', NEW.CPF;
    ELSIF TG_OP = 'UPDATE' AND EXISTS (SELECT 1 FROM CLIENTE WHERE CPF = NEW.CPF AND ID_CLIENTE <> NEW.ID_CLIENTE) THEN
        RAISE EXCEPTION 'JA EXISTE OUTRO CLIENTE COM O CPF %', NEW.CPF;
    ELSIF NEW.NOME IS NULL OR NEW.NOME = '' THEN
        RAISE EXCEPTION 'O NOME DO CLIENTE NAO PODE SER NULO OU VAZIO';
    ELSIF NEW.TELEFONE IS NULL OR NEW.TELEFONE = '' THEN
        RAISE EXCEPTION 'O TELEFONE DO CLIENTE NAO PODE SER NULO OU VAZIO';
    ELSIF CHAR_LENGTH(NEW.TELEFONE) NOT BETWEEN 12 AND 13 THEN
        RAISE EXCEPTION 'O TELEFONE DEVE TER ENTRE 12 E 13 DIGITOS';
    ELSIF NEW.TELEFONE ~ '[^0-9]' THEN
        RAISE EXCEPTION 'O TELEFONE DEVE CONTER APENAS DIGITOS NUMERICOS';
    ELSIF NEW.EMAIL IS NULL OR NEW.EMAIL = '' THEN
        RAISE EXCEPTION 'O EMAIL DO CLIENTE NAO PODE SER NULO OU VAZIO';
    ELSIF NEW.EMAIL NOT ILIKE '%@%.%' THEN
        RAISE EXCEPTION 'O EMAIL INFORMADO NAO ESTA EM UM FORMATO VALIDO';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

