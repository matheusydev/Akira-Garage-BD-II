CREATE OR REPLACE FUNCTION RELATORIO_FATURAMENTO(P_ANO INT, P_MES INT)
RETURNS TABLE (
    TOTAL_OS     INT,
    FATURAMENTO  FLOAT,
    TICKET_MEDIO FLOAT
) AS $$
DECLARE
    V_TOTAL INT;
    V_SOMA  FLOAT;
    V_MEDIA FLOAT;
BEGIN
    IF P_MES < 1 OR P_MES > 12 THEN
        RAISE EXCEPTION 'MES INVALIDO: INFORME UM VALOR ENTRE 1 E 12.';
    END IF;

    SELECT COUNT(*), COALESCE(SUM(VALOR_FINAL), 0), COALESCE(AVG(VALOR_FINAL), 0)
    INTO V_TOTAL, V_SOMA, V_MEDIA
    FROM OS
    WHERE STATUS = 'F'
      AND EXTRACT(YEAR  FROM DT_FECHA_OS) = P_ANO
      AND EXTRACT(MONTH FROM DT_FECHA_OS) = P_MES;

    RETURN QUERY
    SELECT V_TOTAL, V_SOMA, V_MEDIA;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION RELATORIO_PECAS_MAIS_USADAS()
RETURNS TABLE (
    ID_PECA       INT,
    NOME_PECA     VARCHAR,
    TOTAL_USADA   INT,
    TOTAL_VENDIDO FLOAT
) AS $$
BEGIN
    RETURN QUERY
    SELECT
        P.ID_PECA,
        P.NOME,
        SUM(OP.QUANTIDADE)                    AS TOTAL_USADA,
        SUM(OP.QUANTIDADE * P.VALOR_UNITARIO) AS TOTAL_VENDIDO
    FROM OS_PECA OP
    JOIN PECA P ON P.ID_PECA = OP.ID_PECA
    JOIN OS   O ON O.ID_OS   = OP.ID_OS
    WHERE O.STATUS = 'F'
    GROUP BY P.ID_PECA, P.NOME
    ORDER BY TOTAL_USADA DESC;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION CALCULAR_COMISSAO(
    P_ID_FUNCIONARIO INT,
    P_ANO            INT,
    P_MES            INT
) RETURNS FLOAT AS $$
DECLARE
    V_NOME_FUNC  VARCHAR;
    V_NOME_CARGO VARCHAR;
    V_COMISSAO   FLOAT;
    V_TOTAL_SERV FLOAT;
    V_RESULTADO  FLOAT;
    V_PERC       INT;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM FUNCIONARIO WHERE ID_FUNCIONARIO = P_ID_FUNCIONARIO) THEN
        RAISE EXCEPTION 'FUNCIONARIO DE ID % NAO ENCONTRADO.', P_ID_FUNCIONARIO;
    END IF;
    IF P_MES < 1 OR P_MES > 12 THEN
        RAISE EXCEPTION 'MES INVALIDO: INFORME UM VALOR ENTRE 1 E 12.';
    END IF;

    SELECT F.NOME, C.NOME, C.COMISSAO
    INTO V_NOME_FUNC, V_NOME_CARGO, V_COMISSAO
    FROM FUNCIONARIO F
    JOIN CARGO C ON C.ID_CARGO = F.ID_CARGO
    WHERE F.ID_FUNCIONARIO = P_ID_FUNCIONARIO;

    SELECT COALESCE(SUM(S.VALOR), 0)
    INTO V_TOTAL_SERV
    FROM OS_SERVICO OSS
    JOIN OS O ON O.ID_OS = OSS.ID_OS
    JOIN SERVICO S ON S.ID_SERVICO = OSS.ID_SERVICO
    WHERE S.ID_FUNCIONARIO = P_ID_FUNCIONARIO
      AND O.STATUS = 'F'
      AND EXTRACT(YEAR  FROM O.DT_FECHA_OS) = P_ANO
      AND EXTRACT(MONTH FROM O.DT_FECHA_OS) = P_MES;

    V_RESULTADO := V_TOTAL_SERV * V_COMISSAO;
    V_PERC      := CAST(V_COMISSAO * 100 AS INT);

    RAISE NOTICE 'FUNCIONARIO: % | CARGO: % | TOTAL EM SERVICOS: R$% | COMISSAO (% por cento de %/%): R$%',
        V_NOME_FUNC, V_NOME_CARGO, V_TOTAL_SERV, V_PERC, P_MES, P_ANO, V_RESULTADO;

    RETURN V_RESULTADO;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION RELATORIO_COMISSOES(P_ANO INT, P_MES INT)
RETURNS TABLE (
    ID_FUNC        INT,
    NOME_FUNC      VARCHAR,
    CARGO          VARCHAR,
    TOTAL_SERVICO  FLOAT,
    COMISSAO_PERC  FLOAT,
    VALOR_COMISSAO FLOAT
) AS $$
BEGIN
    IF P_MES < 1 OR P_MES > 12 THEN
        RAISE EXCEPTION 'MES INVALIDO: INFORME UM VALOR ENTRE 1 E 12.';
    END IF;

    RETURN QUERY
    SELECT
        F.ID_FUNCIONARIO,
        F.NOME,
        C.NOME,
        COALESCE(SUM(S.VALOR), 0)               AS TOTAL_SERVICO,
        C.COMISSAO,
        COALESCE(SUM(S.VALOR), 0) * C.COMISSAO AS VALOR_COMISSAO
    FROM FUNCIONARIO F
    JOIN CARGO C ON C.ID_CARGO = F.ID_CARGO
    LEFT JOIN SERVICO    S   ON S.ID_FUNCIONARIO = F.ID_FUNCIONARIO
    LEFT JOIN OS_SERVICO OSS ON OSS.ID_SERVICO   = S.ID_SERVICO
    LEFT JOIN OS         O   ON O.ID_OS           = OSS.ID_OS
                             AND O.STATUS = 'F'
                             AND EXTRACT(YEAR  FROM O.DT_FECHA_OS) = P_ANO
                             AND EXTRACT(MONTH FROM O.DT_FECHA_OS) = P_MES
    GROUP BY F.ID_FUNCIONARIO, F.NOME, C.NOME, C.COMISSAO
    ORDER BY VALOR_COMISSAO DESC;
END;
$$ LANGUAGE plpgsql;

-- FUNÇÃO DE VALIDAÇÃO
CREATE OR REPLACE FUNCTION VALIDAR_PECA()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.ID_PECA IS NULL THEN
        RAISE EXCEPTION 'O ID DA PECA NAO PODE SER NULO';
    ELSIF NEW.ID_PECA < 0 THEN
        RAISE EXCEPTION 'O ID DA PECA NAO PODE SER NEGATIVO';
    ELSIF TG_OP = 'INSERT' AND EXISTS (SELECT 1 FROM PECA WHERE ID_PECA = NEW.ID_PECA) THEN
        RAISE EXCEPTION 'JA EXISTE UMA PECA COM O ID %', NEW.ID_PECA;
    ELSIF NEW.ID_FABRICANTE IS NULL THEN
        RAISE EXCEPTION 'O ID DO FABRICANTE NAO PODE SER NULO';
    ELSIF NOT EXISTS (SELECT 1 FROM FABRICANTE WHERE ID_FABRICANTE = NEW.ID_FABRICANTE) THEN
        RAISE EXCEPTION 'O FABRICANTE DE ID % NAO ESTA CADASTRADO', NEW.ID_FABRICANTE;
    ELSIF NEW.NOME IS NULL OR NEW.NOME = '' THEN
        RAISE EXCEPTION 'O NOME DA PECA NAO PODE SER NULO OU VAZIO';
    ELSIF NEW.VALOR_UNITARIO IS NULL OR NEW.VALOR_UNITARIO <= 0 THEN
        RAISE EXCEPTION 'O VALOR UNITARIO DA PECA DEVE SER MAIOR QUE ZERO';
    ELSIF NEW.ESTOQUE IS NULL OR NEW.ESTOQUE < 0 THEN
        RAISE EXCEPTION 'O ESTOQUE NAO PODE SER NULO OU NEGATIVO';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER DISPARAR_VALIDAR_PECA
BEFORE INSERT OR UPDATE ON PECA 
FOR EACH ROW
EXECUTE PROCEDURE VALIDAR_PECA();

