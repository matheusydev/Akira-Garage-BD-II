    RAISE NOTICE 'PECA "%" (% un. x R$%) ADICIONADA A OS %.', V_NOME_PECA, P_QUANTIDADE, V_VALOR_UNIT, P_ID_OS;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION FECHAR_OS(P_ID_OS INT) RETURNS VOID AS $$
DECLARE
    V_STATUS      VARCHAR(1);
    V_VALOR_FINAL FLOAT;
BEGIN
    SELECT STATUS, VALOR_FINAL INTO V_STATUS, V_VALOR_FINAL
    FROM OS WHERE ID_OS = P_ID_OS;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'OS DE ID % NAO ENCONTRADA.', P_ID_OS;
    END IF;
    IF V_STATUS = 'F' THEN
        RAISE EXCEPTION 'A OS DE ID % JA SE ENCONTRA FECHADA.', P_ID_OS;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM OS_SERVICO WHERE ID_OS = P_ID_OS) THEN
        RAISE EXCEPTION 'NAO E POSSIVEL FECHAR A OS %: NENHUM SERVICO FOI ADICIONADO.', P_ID_OS;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM OS_PECA WHERE ID_OS = P_ID_OS) THEN
        RAISE EXCEPTION 'NAO E POSSIVEL FECHAR A OS %: NENHUMA PECA FOI ADICIONADA.', P_ID_OS;
    END IF;
    UPDATE OS
    SET STATUS      = 'F',
        DT_FECHA_OS = CURRENT_DATE
    WHERE ID_OS = P_ID_OS
      AND STATUS  = 'A';
    RAISE NOTICE 'OS % FECHADA EM %. VALOR TOTAL: R$%.', P_ID_OS, CURRENT_DATE, V_VALOR_FINAL;
END;
$$ LANGUAGE plpgsql;

