CREATE OR REPLACE FUNCTION DISPARAR_ALERTA_ESTOQUE()
RETURNS TRIGGER AS $$
DECLARE
    V_LIMITE_PADRAO INT := 25; 
BEGIN

    IF (NEW.ESTOQUE <= V_LIMITE_PADRAO AND NEW.ESTOQUE < OLD.ESTOQUE) THEN
        
        RAISE WARNING 'ALERTA DE ESTOQUE!!!!: A peça "%" (ID: %) caiu para % unidades!', 
			NEW.NOME, NEW.ID_PECA, NEW.ESTOQUE;
                      
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION CALCULAR_COMISSAO_FUNCIONARIO(P_ID_FUNCIONARIO INT)
RETURNS FLOAT AS $$
DECLARE
    V_NOME_FUNC  VARCHAR;
    V_NOME_CARGO VARCHAR;
    V_SALARIO    FLOAT;
    V_COMISSAO   FLOAT;
    V_RESULTADO  FLOAT;
BEGIN


    IF NOT EXISTS (SELECT 1 FROM FUNCIONARIO WHERE ID_FUNCIONARIO = P_ID_FUNCIONARIO) THEN
        RAISE EXCEPTION 'FUNCIONÁRIO COM ID % NÃO ENCONTRADO.', P_ID_FUNCIONARIO;
    END IF;

    SELECT F.NOME, C.NOME, F.SALARIO, C.COMISSAO
    INTO V_NOME_FUNC, V_NOME_CARGO, V_SALARIO, V_COMISSAO
    FROM FUNCIONARIO F
    JOIN CARGO C ON C.ID_CARGO = F.ID_CARGO
    WHERE F.ID_FUNCIONARIO = P_ID_FUNCIONARIO;

    V_RESULTADO := V_SALARIO * V_COMISSAO;

    RAISE NOTICE 'FUNCIONÁRIO: % | CARGO: % | SALÁRIO: R$% | COMISSÃO (% %%): R$%',
        V_NOME_FUNC, V_NOME_CARGO, V_SALARIO,(V_COMISSAO * 100), V_RESULTADO;

    RETURN V_RESULTADO;
END;
$$ LANGUAGE PLPGSQL;

