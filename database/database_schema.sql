CREATE OR REPLACE FUNCTION VALIDAR_CLIENTE()
RETURNS TRIGGER AS $$
BEGIN
IF (NEW.ID_CLIENTE IS NULL) THEN
RAISE EXCEPTION 'O ID DE CLIENTE NÃO PODE SER NULO';
ELSIF (NEW.ID_CLIENTE < 0) THEN
RAISE EXCEPTION 'O ID DE CLIENTE NÃO PODE SER NEGATIVO';
ELSIF EXISTS (SELECT ID_CLIENTE FROM CLIENTE WHERE ID_CLIENTE = NEW.ID_CLIENTE) THEN
RAISE EXCEPTION 'NÃO SÃO PERMITIDOS IDS DUPLICADOS';
ELSIF (NEW.CPF IS NULL) THEN
RAISE EXCEPTION 'O CPF DE CLIENTE NÃO PODE SER NULO';
ELSIF (LENGTH(NEW.CPF) <> 11) THEN
RAISE EXCEPTION 'O CPF INFORMADO DEVE TER 11 DIGITOS';
ELSIF EXISTS(SELECT CPF FROM CLIENTE WHERE CPF = NEW.CPF) THEN
RAISE EXCEPTION 'NÃO SÃO PERMITIDOS CPFS DUPLICADOS';
ELSIF (NEW.NOME IS NULL) THEN
RAISE EXCEPTION 'O NOME INFORMADO NÃO PODE SER NULO';
ELSIF (NEW.TELEFONE IS NULL) THEN
RAISE EXCEPTION 'O TELEFONE INFORMADO NÃO PODE SER NULO';
ELSIF (LENGTH(NEW.TELEFONE) <> 13) THEN
RAISE EXCEPTION 'O TELEFONE DEVE TER 13 DIGITOS';
ELSIF (NEW.EMAIL IS NULL) THEN
RAISE EXCEPTION 'O EMAIL INFORMADO NÃO PODE SER NULO';
ELSIF (NEW.EMAIL NOT ILIKE '%@email.com') THEN
RAISE EXCEPTION 'O EMAIL INFORMADO PRECISA ESTAR NO FORMATO CORRETO';

END IF;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;

