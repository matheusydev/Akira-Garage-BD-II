CREATE OR REPLACE FUNCTION CALCULAR_COMISSAO(ID_FUNC INT, ANO INT, MES INT)
RETURNS TABLE (
valor_comissao FLOAT
)
AS $$
DECLARE
	O_ANO INT;
	O_MES INT;
BEGIN	
	SELECT EXTRACT (YEAR FROM DT_FECHA_OS) INTO O_ANO
	FROM OS WHERE DT_FECHA_OS IS NOT NULL AND 
	EXTRACT(YEAR FROM DT_FECHA_OS) = ANO;
	
	SELECT EXTRACT (MONTH FROM DT_FECHA_OS) INTO O_MES
	FROM OS WHERE DT_FECHA_OS IS NOT NULL AND 
	EXTRACT(MONTH FROM DT_FECHA_OS) = MES;

	RETURN QUERY
	SELECT (SUM(S.VALOR) * COMISSAO) VALOR_COMISSAO
	FROM OS O JOIN SERVICO S ON O.ID_SERVICO = S.ID_SERVICO
	JOIN FUNCIONARIO F ON S.ID_FUNCIONARIO = F.ID_FUNCIONARIO JOIN CARGO C ON F.ID_CARGO = C.ID_CARGO
	WHERE DT_FECHA_OS IS NOT NULL AND F.ID_FUNCIONARIO = ID_FUNC AND
	EXTRACT(YEAR FROM DT_FECHA_OS) = O_ANO AND EXTRACT(MONTH FROM DT_FECHA_OS) = O_MES
	GROUP BY F.ID_FUNCIONARIO,F.NOME,COMISSAO
	ORDER BY VALOR_COMISSAO DESC;
END;
$$ LANGUAGE plpgsql;

